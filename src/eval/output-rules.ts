// "편하게 하는 말 말고"처럼 이유가 아닌 자리의 편하게까지 잡으면 맞는 답을 떨어뜨린다.
const GRATITUDE_REASON =
  /(받아 ?주|받아 ?줘|들어 ?주|들어 ?줘|잘 ?해 ?줘서|잘 ?해 ?주니|챙겨 ?줘서|챙겨 ?주니|편해서|편하니까|편하잖아|편하고|편하다|편해지|편해요|편해\n|편해$|편해 |편한 (?!(것|거)보다)|편하게[^\n]{0,20}(돼서|되니까|될 것 같아|되어서|돼요|돼\n|돼$))/;

// 어미만으로 묻는 문장인 게 확실한 것. 반말 의문문은 억양으로만 갈리고(밥 먹었어 / 밥 먹었어?),
// ~예요·~어요는 평서문과 모양이 같아 어미로는 못 가른다. 확실한 것만 넣는다.
// 누나요·라자냐처럼 낱말 끝이 묻는 어미와 겹치는 것은 빼 둔다 — 존댓말 픽스처에서 실제로 나왔다.
const ASK_ENDING = /((?<!누)나요|까요|인가요|신가요|습니까|려나요|(?<!라자)냐)$/;
// 어미로 못 가르는 의문문(다음 주 언제예요 / 그래서 어떻게 됐어)은 의문사로 짐작한다.
// 짐작이라 점수에는 넣지 않고 리포트에 표시만 한다 — 의문사는 묻는 뜻 없이도 들어가서
// (언제 하냐고 물어보는 거야 그 사람이) 위반으로 세면 멀쩡한 문장이 점수를 깎는다.
const ASK_WORD =
  /(언제|어디|누구|누가|왜|어떻게|어떤|무슨|어느|몇|뭘|뭐가|뭐라고)/;
// 의문사가 있어도 묻는 말이 아닌 꼴 — 남의 말 옮기기(언제 하냐고 물어보더라), 간접의문
// (왜 그런지 모르겠어요), 바람(언제 한번 해보고 싶네요), 굳은 표현(언제나·누구나).
const NOT_ASKING =
  /(냐고|라고|다고|더라|물어|여쭤|는지|은지|을지|모르|궁금|싶|언제나|언제든|언제 한번|누구나|누군가|어디든|어디선가|어떻게든|뭔가)/;
// 문장 끝에 붙은 웃음 표기와 여운을 걷어내고 어미를 본다.
const TAIL = /[\s.~!ㅋㅎ]+$/;
// 문장 끝의 냐. 뭐하냐·궁금하냐처럼 끝에 오는 것만 걸고, 냐고·냐는처럼 문장 중간의 것과 라자냐처럼
// 낱말 안의 것은 안 건다(규칙층 SPEECH의 냐 금지, 이슈 #353). 물음표는 TAIL이 안 떼므로 따로 뗀다.
const NYA_END = /(?<!라자)냐$/;
// 말풍선을 여는 감탄사 오. 오 진짜?·오~·오ㅋㅋㅋ처럼 뒤가 끊기는 것만 걸고, 오늘·오랜만·오케이는
// 뒤에 오는 글자로 갈라 안 건다(규칙층 SPEECH의 말머리 오 금지, 이슈 #373).
const OH_OPENER = /^오+(?=[\s,.!?~ㅋㅎ]|$)/;
// 1단계에서 아직 안 하는 말. 좋아해·보고 싶다는 사물을 두고도 쓰는 말이라 상대를 가리키는 말이
// 앞에 올 때만 걸고, 네가 좋아하는 노래·네가 보고 싶다는 영화·네가 좋아 보여는 통과다.
const YOU = "(?:너|널|네가|니가|너를|너가)\\s?(?:진짜|정말|좀|많이|되게|엄청|너무|자꾸)?\\s?";
const STAGE1_NOT_YET = new RegExp(
  [
    `${YOU}좋아(?!\\s?보[이여인])(?:해|한다|하나 ?봐|하는 것 같|하는 거 같|해서|하니까|한다고|해요|합니다|하는데|하잖아|하게 됐|하게 된|$|[.!~\\s])`,
    `${YOU}보고 ?싶(?!다는|다던|다고 한|어 ?하는|어 ?했)`,
    "좋아하나 ?봐",
    "좋아하게 ?(?:됐|된)",
    "질투",
    "삐[지질졌침]",
    "너한테만",
    "너에게만",
    "너밖에",
    "귀엽",
    "귀여",
    "특이하",
    "특이해",
    "특이한",
    "답장.{0,6}(?:왜|좀|빨리)",
    "왜 이제 (?:봐|봤|답|읽|와|왔)",
    "읽씹",
  ].join("|"),
  "m",
);
// 이유 없이 상대 생각이 났다는 말. 1단계는 하루에서 만난 것에 얹어서만 말한다.
const BASELESS_THOUGHT =
  /(?:그냥|갑자기|문득|괜히|뜬금없이|이유 없이|아무 이유 없이)\s?(?:네|너|니)\s?생각/;
// 근거 없이 치켜세우는 말. 상대가 한 말이나 행동 하나를 짚는 감탄은 여기 안 걸린다.
const FLATTERY =
  /(?:대단하|대단해|멋있|멋지|훌륭|존경스|기특|자랑스|천재|(?:너|네가|니가)\s?(?:진짜|정말)?\s?최고)/;
// 나중에 연락하겠다는 말. 말풍선 어디에 있어도 본다 — 뒤에 물음이 이어져도 앞 말풍선에 ~인데로
// 이유가 붙으면 지금은 말 걸지 말라는 뜻이 된다(이슈 #368). 아까 다시 연락해서 물어봤다처럼 지난
// 일을 말하는 꼴은 말끝의 부정 조회로 갈라서 안 건다.
const LATER_CONTACT = new RegExp(
  [
    // 끝나면 연락할게 · 이따 다시 연락해 · 퇴근하고 연락 줄게
    "(?:끝나|끝내|마치|퇴근|나가|나갈|들어가|이따|나중에|따로|다시|그때)[^\\n]{0,10}연락[^\\n]{0,4}(?:할게|할께|하자|해(?!서|봤|보니|본|야)|줘|줄게|드릴|할 테|할까)",
    // 이따 얘기하자 · 나중에 말해 · 내일 얘기해
    "(?:이따|나중에|내일|끝나고|끝나면|다음에|그때)[^\\n]{0,4}(?:얘기|이야기|말)(?:하자|해|해요|하죠|할게|할까|나누)",
  ].join("|"),
  "m",
);
// 상대를 보내는 말. 마지막 말풍선에서만 본다 — 씻고 바로 누워처럼 챙기는 말끝은 가운데 말풍선에서
// 맞는 말이고, 하고 나서 말해 달라는 말(눕고 나서 나한테 말해)은 이어 가는 말이라 안 건다.
const SEND_OFF = new RegExp(
  [
    // 푹 쉬어 · 얼른 자 · 이제 들어가 봐 · 조심히 들어가 · 먼저 가
    "(?:푹|잘|좀|얼른|빨리|일단|먼저|이제|바로|일찍|조심히|조심해서)\\s?(?:쉬어|쉬세요|자|자요|주무세요|들어가|들어가요|들어가 ?봐|들어가 ?봐요|누워|누워요|씻어|씻어요|가|가요)$",
    // 쉬어 · 들어가 봐 · 잘 자로 끝나는 말풍선
    "(?:쉬어|쉬세요|주무세요|들어가 ?봐|들어가 ?봐요|들어가 ?보세요|잘 ?자|잘 ?자요|굿나잇|좋은 꿈 꿔)$",
    // 이따 봐 · 내일 보자
    "(?:이따|나중에|내일|다음에)\\s?(?:봐|봐요|보자|보자고|뵈어요|뵐게요)$",
    "그대로 있어",
    "고생 ?(?:많았|했|하셨)",
    "수고 ?(?:많았|했|하셨)",
  ].join("|"),
  "m",
);
// 상대 말을 풀어 되돌려주는 꼴과 대본처럼 지지를 선언하는 말. 속상한 말이 여러 개 온 자리에서만
// 본다 — 그래서 답이 없었구나 같은 한 마디 반응은 여기 안 걸리게 거가 붙은 꼴만 잡는다.
const MIRROR = new RegExp(
  [
    "[가-힣] (?:거네|거였네|거구나|거였구나|거잖아|거였잖아)(?:요)?(?:$|[\\s.~!?ㅋㅎ])",
    "다 싶(?:어|었|네|다|겠|더)",
    "(?:나|내가)\\s?(?:여기|옆에)\\s?있(?:어|을게|잖아|으니까)",
    "옆에서[^\\n]{0,8}(?:힘|응원|같이)",
    "힘\\s?(?:실어|보태|이 ?돼 ?줄|이 ?되어 ?줄)",
    "같이 있어\\s?줄",
    "언제든\\s?(?:말해|얘기해|연락해)",
    "들어\\s?줄(?:게|테니)",
    "(?:힘들었|속상했|서운했|답답했|억울했|막막했|허무했|아쉬웠|섭섭했|속상하|힘들)겠(?:다|네|어|어요|네요|지)",
  ].join("|"),
  "m",
);

const toLines = (bubbles: string[]): string[] =>
  bubbles
    .flatMap((b) => b.split("\n"))
    .map((l) => l.trim().replace(TAIL, ""))
    .filter(Boolean);

const looksLikeAsking = (line: string): boolean =>
  ASK_WORD.test(line) && !NOT_ASKING.test(line);

const marksIn = (text: string): string[] => text.match(LAUGH) ?? [];

/** 답장에 나온 웃음 표기 덩이들. ㅋㅋ 하나가 한 덩이다. */
export const laughMarks = (bubbles: string[]): string[] =>
  marksIn(bubbles.join("\n"));

/**
 * 한 말풍선 안에서 웃음 자음을 섞어 쓴 말풍선. ㅋㅋ와 ㅋㅋㅋ는 같은 종류라 통과하고,
 * ㅋㅋ와 ㅎㅎ가 한 말풍선에 같이 있으면 걸린다. 말풍선이 다르면 섞어 써도 된다.
 */
export const mixedLaughBubble = (bubbles: string[]): string | null =>
  bubbles.find((b) => new Set(marksIn(b).flatMap((m) => [...m])).size > 1) ??
  null;

/**
 * 개수가 모자란 웃음 표기 덩이. ㅋ는 셋 이상, ㅎ는 둘 이상만 쓰기로 해서(이슈 #324) ㅋ·ㅋㅋ와
 * ㅎ 하나가 걸린다. ㅋㅋㅋ와 ㅎㅎ는 통과하고, 한 덩이에 ㅋ와 ㅎ가 섞인 것은 섞어 쓴 쪽 규칙이 잡는다.
 */
export const shortLaughMarks = (bubbles: string[]): string[] =>
  laughMarks(bubbles).filter((m) => {
    const k = (m.match(/ㅋ/g) ?? []).length;
    const h = (m.match(/ㅎ/g) ?? []).length;
    if (k > 0 && h > 0) return false;
    return (k > 0 && k < 3) || h === 1;
  });

/** 확실한 의문 종결어미인데 물음표로 끝나지 않은 줄. 점수에 넣는 위반이다. */
export const askWithoutMark = (bubbles: string[]): string[] =>
  toLines(bubbles).filter((l) => !l.endsWith("?") && ASK_ENDING.test(l));

/** 의문사가 있는데 물음표가 없는 줄. 짐작이라 점수에 넣지 않고 눈으로 보는 자리다. */
export const suspectQuestions = (bubbles: string[]): string[] =>
  toLines(bubbles).filter(
    (l) => !l.endsWith("?") && !ASK_ENDING.test(l) && looksLikeAsking(l),
  );

/** 이 답장에 질문이 들어 있는가 — 물음표 케이스가 헛돌지 않았는지 보는 자리다. */
export const hasQuestion = (bubbles: string[]): boolean =>
  toLines(bubbles).some(
    (l) => l.includes("?") || ASK_ENDING.test(l) || looksLikeAsking(l),
  );

const firstMatch = (text: string, re: RegExp): string | null =>
  text.match(re)?.[0] ?? null;

/** 냐로 끝나는 줄. 물음표와 웃음 표기는 떼고 본다. */
export const nyaEndings = (bubbles: string[]): string[] =>
  toLines(bubbles)
    .map((l) => l.replace(/[?\s.~!ㅋㅎ]+$/, ""))
    .filter((l) => NYA_END.test(l));

/** 오로 여는 줄. 오늘·오랜만처럼 오로 시작하는 낱말은 걸리지 않는다. */
export const ohOpeners = (bubbles: string[]): string[] =>
  toLines(bubbles).filter((l) => OH_OPENER.test(l));

/** 생각났다는 말이 있는가. 생각났어·생각이 나더라·생각 났다를 다 받는다. */
export const hasThought = (bubbles: string[]): boolean =>
  /생각(?:이|도|은)?\s?(?:났|나)/.test(bubbles.join("\n"));

/** 말풍선마다 마지막 줄. 웃음 표기·기호는 떼고 본다. */
const bubbleEnds = (bubbles: string[]): string[] =>
  bubbles
    .map((b) => b.trim().split("\n").at(-1)?.trim().replace(TAIL, "") ?? "")
    .filter(Boolean);

/**
 * 말풍선 셋 이상이 전부 과거형 평서문으로 끝나거나 끝 두 글자가 같으면 그 끝들을 돌려준다.
 * "아니었어 / 예매해놨어 / 잡았어"가 걸리고, 셋 중 하나가 되묻기나 지금 하는 일이면 통과다.
 */
export const sameEndings = (bubbles: string[]): string[] | null => {
  const ends = bubbleEnds(bubbles);
  if (ends.length < 3) return null;
  const allPast = ends.every((e) => PAST_END.test(e));
  const tails = new Set(ends.map((e) => e.slice(-2)));
  return allPast || tails.size === 1 ? ends : null;
};

/**
 * 말풍선을 규칙에 대본다. 케이스를 가리지 않는 규칙(이모지·큰따옴표·리스트·웃음 표기 일관성·
 * 웃음 표기 개수·의문 종결어미의 물음표·말풍선 끝 어미 반복·추측형 말끝 겹침·하루 은유·문장 끝 냐·
 * 말머리 오)와, 케이스가 켤 때만 보는 웃음 금지 자리·질문의 말 되풀이·좋아하는 이유·
 * 1단계에서 아직 안 하는 말·근거 없이 치켜세우는 말·나중에 연락하겠다는 말·상대를 보내는 말로
 * 닫음·상대 말 되돌려주기다. 빈 배열이면 통과.
 */
export const checkOutputRules = (
  bubbles: string[],
  kase: Pick<
    EvalCase,
    "noLaugh" | "echo" | "whyLike" | "stage1" | "noFlattery" | "noSendOff" | "noMirror"
  >,
): Violation[] => {
  const text = bubbles.join("\n");
  const lastBubble = bubbles.at(-1)?.trim().replace(TAIL, "") ?? "";
  const out: Violation[] = [];

  const later = kase.noSendOff ? firstMatch(text, LATER_CONTACT) : null;
  if (later) out.push({ rule: "나중에 연락하겠다는 말", found: later.trim() });

  const sendOff = kase.noSendOff ? firstMatch(lastBubble, SEND_OFF) : null;
  if (sendOff) out.push({ rule: "상대를 보내는 말로 닫음", found: sendOff });

  const mirror = kase.noMirror ? firstMatch(text, MIRROR) : null;
  if (mirror)
    out.push({ rule: "상대 말 되돌려주기·지지 선언", found: mirror.trim() });

  const nya = nyaEndings(bubbles);
  if (nya.length) out.push({ rule: "문장 끝 냐", found: nya[0] });

  const oh = ohOpeners(bubbles);
  if (oh.length) out.push({ rule: "말머리 오", found: oh[0] });

  const notYet = kase.stage1 ? firstMatch(text, STAGE1_NOT_YET) : null;
  if (notYet) out.push({ rule: "1단계에서 아직 안 하는 말", found: notYet });

  const baseless = kase.stage1 ? firstMatch(text, BASELESS_THOUGHT) : null;
  if (baseless) out.push({ rule: "이유 없이 생각났다는 말", found: baseless });

  const flattery = kase.noFlattery ? firstMatch(text, FLATTERY) : null;
  if (flattery) out.push({ rule: "근거 없이 치켜세우는 말", found: flattery });

  const ends = sameEndings(bubbles);
  if (ends)
    out.push({ rule: "말풍선 끝 같은 어미 반복", found: ends.join(" / ") });

  const hedges = text.match(HEDGE) ?? [];
  if (hedges.length >= 2)
    out.push({ rule: "추측형 말끝 겹침", found: hedges.join(" ") });

  const metaphor = firstMatch(text, TIME_METAPHOR);
  if (metaphor) out.push({ rule: "하루·시간 은유", found: metaphor });

  const echoed = (kase.echo ?? []).find((w) => text.includes(w));
  if (echoed) out.push({ rule: "질문의 말 되풀이", found: echoed });

  const gratitude = kase.whyLike ? firstMatch(text, GRATITUDE_REASON) : null;
  if (gratitude)
    out.push({ rule: "좋아하는 이유를 상대가 해 준 것으로 댐", found: gratitude });

  const emoji = firstMatch(text, EMOJI) ?? firstMatch(text, FACE);
  if (emoji) out.push({ rule: "이모지·그림 이모티콘", found: emoji });

  const quote = firstMatch(text, QUOTE);
  if (quote) out.push({ rule: "큰따옴표", found: quote });

  const md = firstMatch(text, MARKDOWN);
  if (md) out.push({ rule: "리스트·마크다운", found: md.trim() });

  const unmarked = askWithoutMark(bubbles);
  if (unmarked.length)
    out.push({ rule: "묻는 문장에 물음표 없음", found: unmarked[0] });

  const laughs = laughMarks(bubbles);
  const mixed = mixedLaughBubble(bubbles);
  const short = shortLaughMarks(bubbles);
  if (kase.noLaugh && laughs.length)
    out.push({ rule: "웃음 금지 자리", found: laughs.join(" ") });
  else {
    if (mixed)
      out.push({
        rule: "한 말풍선에 웃음 표기 섞어 씀",
        found: marksIn(mixed).join(" "),
      });
    if (short.length)
      out.push({ rule: "웃음 표기 개수 모자람", found: short.join(" ") });
  }

  return out;
};

