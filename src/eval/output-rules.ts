/** 케이스 하나 — 대화 한 토막과, 그 상황에서 더 요구되는 것. */
export interface EvalCase {
  /** 리포트에 찍히는 이름. */
  id: string;
  /** 이 케이스가 무엇을 물고 있는지. */
  about: string;
  /** 마지막 원소가 상대가 방금 보낸 말이다. */
  turns: ChatTurn[];
  /** 웃음 표기가 한 번도 나오면 안 되는 자리인가(다정한 말·상대가 속상할 때). */
  noLaugh?: boolean;
  /** 웃음 표기가 나올 만한 자리인가. 안 나오면 표기 일관성을 재지 못한 것이다. */
  wantsLaugh?: boolean;
  /** 캐릭터가 되물을 수밖에 없는 자리인가. 질문이 안 나오면 물음표 규칙을 재지 못한 것이다. */
  wantsQuestion?: boolean;
  /**
   * 오늘 메모로 남길 것이 나온 자리인가. 위 셋과 달리 표기 통과율이 아니라 메모 통과율로
   * 따로 센다 — 표기는 지금 거의 다 맞고 메모는 거의 안 나와서, 한 숫자에 섞으면 어느 쪽이
   * 움직였는지 안 갈린다.
   */
  wantsNote?: boolean;
  /**
   * 그 자리에서 나와야 하는 메모 건수. 안 적으면 1건이다.
   *
   * 한 턴에 남길 것이 둘인 자리가 있다 — 상대가 말해 준 사실과 캐릭터가 처음 꺼낸 자기 이야기가
   * 같이 나오는 턴이 그렇다(이슈 #399). 거기서 한 줄만 오면 다음에 같은 것을 물었을 때 다른 답이
   * 나오므로, 건수까지 봐야 고친 것이 재진다.
   */
  wantsNotes?: number;
  /**
   * 플러팅을 쓸 만한 자리인가. 메모와 같은 방식으로 따로 세고, 여기도 표기 통과율에 섞지 않는다
   * (이슈 #385). 위반이 아니라 태그가 왔는지만 보는 칸이라, 안 왔다고 케이스가 실패하지 않는다.
   */
  wantsMove?: boolean;
  /**
   * 상대의 물음에 들어 있던 말 가운데 답에 다시 나오면 안 되는 것. 왜냐고 물으면 그 전제를
   * 답의 앞뒤에 되풀이하는 버릇을 잰다(이슈 #281). 케이스가 켤 때만 본다.
   */
  echo?: string[];
  /**
   * 왜 좋으냐·왜 편하냐고 물은 자리인가. 상대가 해 준 것(들어줘서·받아줘서·편해서)으로 이유를
   * 대면 위반이다 — 좋아하는 이유는 캐릭터 쪽에서 나와야 한다는 규칙을 잰다(이슈 #285).
   * 케이스가 켤 때만 본다. 다른 자리에서는 들어주는 게 좋다는 말이 규칙에 맞는 말이라서다.
   */
  whyLike?: boolean;
  /**
   * 1단계에서 아직 안 하는 말(보고 싶다·좋아한다·질투·삐침·너한테만·귀엽다·특이하다·상대 답장
   * 속도 타박)이 나오면 위반이다. 단계 블록이 시키는 것을 재고, 평가 픽스처는 1단계로 깔린다
   * (이슈 #353). 이유 없이 네 생각이 났다는 말도 같이 본다. 케이스가 켤 때만 본다 — 다른 자리의
   * 좋아해·귀엽다는 사물을 두고 하는 말일 수 있어서다.
   */
  stage1?: boolean;
  /**
   * 대단하다·멋있다처럼 근거 없이 치켜세우는 말이 나오면 위반이다. 칭찬은 상대가 한 말이나 행동
   * 하나를 짚어서만 한다는 규칙층 문장을 잰다(이슈 #353). 케이스가 켤 때만 본다.
   */
  noFlattery?: boolean;
  /**
   * 나중에 연락하겠다는 말이 어느 말풍선에든 있거나, 마지막 말풍선이 상대를 보내는 말이면
   * 위반이다. 끝나면 연락할게·이따 얘기하자·푹 쉬어·얼른 들어가 봐·고생 많았어처럼 대화를 접는
   * 말로 닫는 버릇을 잰다(이슈 #364·#368). 케이스가 켤 때만 본다 — 정말 자러 가는 자리에서는
   * 잘 자가 맞는 말이라서다.
   */
  noSendOff?: boolean;
  /**
   * 상대 말을 풀어 되돌려주거나 대본처럼 지지를 선언하면 위반이다. ~는 거네·~다 싶어로 상대 말을
   * 되돌리는 꼴, 속상했겠다처럼 감정에 이름을 붙이는 말, 나 여기 있어·옆에서 힘 실어 줄게 같은
   * 말을 잰다(이슈 #364). 케이스가 켤 때만 본다 — 속상한 말이 여러 개 온 자리가 아니면 그런
   * 꼴이 나올 일이 드물고, 한 거네는 평범한 되묻기에도 붙어서다.
   */
  noMirror?: boolean;
  /** 생각났다는 말이 나올 자리인가. 안 나오면 그 말을 사물에 얹는지를 재지 못한 것이다. */
  wantsThought?: boolean;
}

/** 채점기 하나가 걸어 낸 위반. */
