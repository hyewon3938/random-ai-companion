// 누나 이야기를 처음 꺼낸 답장에 메모가 안 붙었다. 다른 하나는 자리를 비운 사이 쌓인 말에
// 한 번에 답하는 자리다. 운영에서 메모가 가장 안 나온 자리가 여기라, 마커가 붙은 유저 턴
// 하나에 여러 통을 넣어 기록의 모양까지 같게 맞췄다.
//
// 몰아 답장 케이스의 기록에는 앞 답장이 실제로 적은 메모가 들어 있다(아래 noted). 운영 기록이
// 그렇게 바뀌었기 때문인데(이슈 #346), 앞 케이스들이 재던 빈 칸 조건보다 쉬운 자리라 두 값을
// 나란히 두고 비교하지 않는다.
//
// 여섯 번째와 일곱 번째는 이슈 #399가 더한 것이다. 하나는 앞 메모와 같은 주제의 더 좁은 값이
// 나온 자리다 — 이미 적은 것을 다시 적지 말라는 문장에 걸려 동네를 말한 턴의 메모가 빠졌다.
// 다른 하나는 한 턴에 남길 것이 둘인 자리로, 건수까지 본다(wantsNotes).
//
// 긴 쪽의 앞 대화가 남길 것 없는 잡담인 것도 일부러다. 앞에서 메모할 거리가 나오면 그 자리가
// 통과의 이유가 되어, 마지막 한 마디를 봤는지 못 봤는지가 안 갈린다. 이 케이스를 반복해 잴
// 때는 yarn eval --only=긴기록.
//
// 규칙층(src/prompts/reply.ts의 OUTPUT_FORMAT)이 시키는 것을 모델이 실제로 지키는지 잰다. 규칙을 고치면
// 지키는 정도가 같이 움직이는데, 지금까지는 배포하고 며칠 대화를 눈으로 읽어야 알 수 있었다
// (이슈 #222의 웃음 표기가 그랬다). 케이스를 고정해 두면 프롬프트를 고친 자리에서 바로 잰다.
//
// 채점은 전부 규칙 기반이다 — 모델에게 채점을 시키면(LLM-as-Judge) 채점자가 흔들려서
// 프롬프트 변경분과 채점 잡음을 가를 수 없다. 글자로 가려지는 규칙부터 덮는다.
//
// 관계 단계가 들어오면서(이슈 #353) 케이스가 재는 것이 하나 늘었다. 답장 규칙층은 어느 단계든
// 같지만 단계 블록(prompts/relationship.ts)은 1단계에서 아직 안 하는 말을 따로 두는데, 평가
// 픽스처는 1단계로 깔리므로 그 말이 안 나오는지를 케이스가 켤 때만 잰다(stage1). 근거 없이
// 치켜세우는 말(noFlattery)과 문장 끝 냐는 규칙층 문장이라 단계를 가리지 않고, 냐는 케이스도
// 가리지 않는다.
//
// 9/10 피드백(이슈 #364)으로 케이스가 켤 때만 보는 것이 둘 더 늘었다 — 상대를 보내는
// 말인지(noSendOff)와 상대 말을 되돌려주거나 지지를 선언하는지(noMirror). 둘 다 자리를
// 가린다. 잘 자는 정말 자러 갈 때 맞는 말이고, ~잖아는 속상한 말을 받는 자리가 아니면 평범한 말끝이다.
//
// noSendOff는 두 가지를 따로 본다(이슈 #368). 나중에 연락하겠다는 말은 말풍선 어디에 있어도
// 위반이고, 상대를 보내는 말은 마지막 말풍선에서만 위반이다. 앞 말풍선의 연락 예고는 뒤에 물음이
// 이어지면 괜찮다고 두었는데, 앞 말풍선에 ~인데로 이유가 붙으면 그 물음이 형식만 남는다.
//
// 말머리 오도 케이스를 가리지 않는다(이슈 #373). 규칙층이 말풍선을 오로 열지 말라고 하는데
// 모델이 습관처럼 쓰던 자리라, 골든셋 기록의 캐릭터 발화에서도 같은 말머리를 뺐다 — 기록의
// 모양을 모델이 따라가므로 케이스가 위반을 가르치고 있었다.
//
// 재는 것이 이슈 #385로 하나 더 늘었다. 답장 객체에서 늘 넣기로 한 칸 셋(note·move·first)이
// 실제로 실려 오는지는 케이스를 안 가리고 전부가 함께 재고(run.ts의 slots), 그 가운데 플러팅
// 코드가 값까지 붙어 오는지는 wantsMove 케이스 둘이 잰다. 둘을 나눈 이유는 실패하는 방식이
// 달라서다 — 칸이 아예 안 오는 것은 형식의 실패라 모든 답장에서 같이 나고, 칸은 왔는데 늘
// null인 것은 모델이 플러팅을 안 썼거나 쓰고도 이름을 못 붙인 것이라 자리를 골라야 보인다.
//
// 플러팅 케이스가 둘뿐이고 하한이 0인 이유는 이 자리에 정답이 하나가 아니어서다. 챙기는 말도
// 농담도 안 하고 그냥 되묻는 답이 규칙을 어기는 것은 아니라, 태그가 안 온 회차를 실패로 세면
// 규칙을 안 고쳤는데도 숫자가 흔들린다. 실제 플러팅 빈도는 운영에서 본다. 여기서 보려는 것은
// 모델이 코드 목록을 알아보고 값으로 쓸 줄 아는지다.
//
// 이 파일은 DB도 API도 열지 않는다. 케이스를 실제로 태우는 자리는 run.ts다.

