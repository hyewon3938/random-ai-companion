/**
 * 문장에서 표에 있는 이벤트 이름을 찾는다. 이름과 별칭을 다 보고, notMatch에 걸린 말은 먼저 지운다.
 *
 * 월 리듬이 이 달 재료(아크·진행 중인 일·이미 잡힌 일정)를 한 덩어리로 넘겨 쓴다. 걸린 이름만큼만
 * 절차가 프롬프트에 들어가고 아무것도 안 걸리면 빈 배열이라, 그 달 프롬프트에는 문화 스크립트가
 * 한 줄도 안 실린다.
 */
export const findCultureEvents = (text: string): string[] => {
  const found: string[] = [];
  for (const a of EVENT_ALIASES) {
    let hay = text;
    for (const n of a.notMatch) hay = hay.split(n).join(" ");
    if ([a.event, ...a.aliases].some((w) => hay.includes(w)))
      found.push(a.event);
  }
  return found;
};
