// 축의금 시세, 명절 승차권 대기열처럼 한국에서 자란 사람은 아는데 모델이 그 자리에서 안 꺼내는
// 것들이다. 절차만 적으면 순서는 맞고 결은 어긋난 하루가 나온다.
//
// 표에 값을 넣고 빼는 함수가 없어 표 묶음 파일이 아니다 — 원본과 그 원본만 보는 찾기 함수뿐이라
// 아무것도 import하지 않는다.

/** 지금 있는 국적은 하나뿐이다. 부르는 쪽이 국적을 안 적으면 이 값으로 본다. */
export const DEFAULT_LOCALE = "KR";

/** 이벤트 하나에 역할 하나. 같은 이벤트라도 역할이 다르면 다른 줄이 된다. */
export interface CultureScript {
  /** 나중에 국적별로 나눌 자리. 지금은 KR 한 갈래뿐이다. */
  locale: string;
  /** 이벤트 이름. 진행 중인 일이나 아크의 문장에서 이 이름을 찾는다. */
  event: string;
  /** 이 이벤트에서 캐릭터가 선 자리. 본인·형제자매·친구처럼 하는 일이 갈리는 단위로 적는다. */
  role: string;
  /** 순서대로. 표에 넣을 때 여기 순서가 step_no가 된다. */
  steps: CultureStep[];
}

export interface CultureStep {
  /** 이벤트 당일에서 거꾸로 센 날 수. 당일이 0이고, 당일보다 뒤면 음수. */
  daysBefore: number;
  /** 그 단계에서 캐릭터가 하는 일. */
  step: string;
}

/**
 * 이벤트 이름을 문장에서 찾을 때 쓰는 별칭. 아크는 명절이라고 안 적고 추석이라고 적는다.
 *
 * notMatch는 이벤트 이름을 품고 있지만 그 이벤트가 아닌 말이다. 이사회에 들어간 이사, 승진 심사에
 * 들어간 승진처럼 겹쳐 걸리는 자리를 여기서 막는다. 찾는 쪽은 notMatch를 먼저 지우고 나서
 * 이름과 별칭을 찾는다.
 */
