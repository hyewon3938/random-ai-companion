// 발화 말풍선 후처리 — LLM 출력의 기계 티(큰따옴표·쉼표·물음표 누락/오부착)를 지우는 최종 방어선.
// bot.ts는 import만으로 봇이 기동되는 부작용이 있어, 이 판정 로직만 순수 함수로 분리해
// 단독 스크립트로 회귀 검증할 수 있게 했다(물음표 보정은 오탐 사례가 반복돼 온 부분).

// 큰따옴표는 특유의 AI 느낌이라 발화에서 지운다(인용·강조 모두 따옴표 없이).
export const stripDquotes = (s: string): string => s.replace(/[“”„‟"]/gu, "");

// 쉼표도 마찬가지 — 사람은 메신저에서 쉼표를 거의 안 찍는다. 한글 사이와 말풍선 끝의
// 쉼표만 지운다(1,000 같은 숫자 표기나 영문 안의 쉼표는 그대로).
export const stripCommas = (s: string): string =>
  s
    .replace(/([가-힣ㄱ-ㅎㅏ-ㅣ])\s*,\s*(?=[가-힣ㄱ-ㅎㅏ-ㅣ0-9])/gu, "$1 ")
    .replace(/([가-힣ㄱ-ㅎㅏ-ㅣ])\s*,+\s*$/u, "$1");

// 물음표 보정: 질문인데 물음표가 빠진 말풍선을 고친다(LLM이 자꾸 흘려서 코드가 최종 방어선).
// 평서문에 붙는 오탐이 물음표 누락보다 훨씬 어색하므로 판정은 철저히 보수적으로 —
// 의문 전용 종결어미이거나, 의문사가 문장 끝머리에서 실제 묻는 역할일 때만 붙이고 애매하면 놔둔다.
// (이전 판은 의문사가 문장 어디에 있든 붙여서 "누가 봐도 네 잘못은 아니야", "몇 년 만이야",
//  "어떻게든 되겠지" 같은 평서문에 물음표가 붙었다.)
const DECLARATIVE_END =
  /(습니다|거든요?|더라고요?|더라구요?|네요|군요|구나|ㄹ게요?|을게요?|잖아요?|라고요?|답니다|던데요?|는데요?|던걸요?|걸요?|겠어요|겠네요|겠다|더라|드라|을게|ㄹ게)$/;

// 의문 전용 종결어미만 남겼다. 평서와 충돌하는 어미는 뺐거나 룩비하인드로 막았다 —
// 나요(만나요·끝나요), 래요(그래요), 래(그래·몰래·바래), 니(봤으니·그러니), 까(하니까·뭐랄까), 디.
const Q_ENDING =
  /((?<!니|랄)까요?|(?<!그|이|저|몰|바)래요?|(?:았|었|였|겠)니|냐|인가요|은가요|는가요|어때요?|어땠어요?)$/u;

// 의문사 자체는 신호가 약하다 — 문장 앞·수식 자리에 오면 대개 평서다("누가 봐도", "얼마 전에").
// 마지막 두 어절 안에 있을 때만 묻는 역할로 인정한다. 얼마는 단독으로는 감탄이 흔해서
// ("얼마 만이야") 서술어와 붙은 꼴만 본다.
const Q_WORD =
  /(뭐|무슨|무엇|뭘|어디|언제|누구|누가|왜|어떻게|어떤|어느|몇|어때|얼마(?:야|예|에|였))/u;
// 의문사가 들어 있어도 묻는 게 아닌 굳은 꼴(뭐든·뭐라도·어떻게든·왜인지·누가 뭐래도 등).
const Q_WORD_FROZEN = /(든|든지|든가|나마|인지|는지|랄까|냐면|니까|도)$/u;
// 의문사가 있어도 이 어미로 끝나면 평서·혼잣말 쪽이 훨씬 흔하다("뭐 그럴 수도 있지") — 붙이지 않는다.
const Q_ADD_BLOCK =
  /(지|죠|네|다|라|자|게|든|도|음|잖아|거든|는데|은데|니까|아서|어서|여서|라고|다고|고|며|지만)$/u;

export const fixQuestion = (bubble: string): string => {
  const t = bubble.replace(/\s+$/u, "");
  if (!t) return bubble;
  // 평서 종결 어미 뒤에 LLM이 잘못 붙인 물음표는 뗀다(자기 설명을 확인 구하듯 끝내는 패턴 방지).
  const q = t.match(/^(.*[^\s?？])[?？]+$/u);
  if (q && DECLARATIVE_END.test(q[1])) return q[1] + ".";
  if (/[?？!！~.…”"』」)\]]$/u.test(t)) return bubble; // 이미 종결부호
  if (/[ㅋㅎ]$/u.test(t)) return bubble; // 웃음으로 끝나면 그대로
  if (DECLARATIVE_END.test(t)) return bubble; // 명백한 평서
  if (Q_ENDING.test(t)) return t + "?";
  const tailAsks = t
    .split(/\s+/u)
    .slice(-2)
    .some((w) => Q_WORD.test(w) && !Q_WORD_FROZEN.test(w));
  if (tailAsks && !Q_ADD_BLOCK.test(t)) return t + "?";
  return bubble;
};

// 말풍선 하나에 후처리 전부 적용. 쉼표·따옴표를 먼저 지워야 물음표 판정이 실제 끝 어미를 본다.
export const polishBubble = (raw: string): string =>
  fixQuestion(stripCommas(stripDquotes(raw)));
